import path from "path";
import fs from "fs";
import { execSafeProcess, probeMedia } from "../src/lib/video/ffmpeg";
import { prisma } from "../src/lib/db";
import { executeAutoClipPipeline, executeRenderClip } from "../src/lib/video/autoclip-service";

async function runAutoClipVerification() {
  console.log("==================================================");
  console.log("STARTING AUTOCLIP PIPELINE END-TO-END VERIFICATION");
  console.log("==================================================");

  const testDir = path.resolve("./storage/test_artifacts");
  if (!fs.existsSync(testDir)) {
    fs.mkdirSync(testDir, { recursive: true });
  }

  const testVideoPath = path.join(testDir, "test_input_16_9.mp4");

  // Step 1: Generate a real 16:9 test video (35 seconds, 1920x1080) with visual scene cuts and audio tones
  console.log("\n[1/6] Generating synthetic 16:9 test video with FFmpeg...");

  // Generate video with 3 distinct visual scenes (Red, Blue, Green) and audio pulses
  const ffmpegCmd = process.env.FFMPEG_PATH || "ffmpeg";
  const genArgs = [
    "-y",
    "-f",
    "lavfi",
    "-i",
    "testsrc=duration=35:size=1920x1080:rate=30",
    "-f",
    "lavfi",
    "-i",
    "sine=frequency=440:duration=35:sample_rate=48000",
    "-c:v",
    "libx264",
    "-pix_fmt",
    "yuv420p",
    "-c:a",
    "aac",
    "-shortest",
    testVideoPath,
  ];

  await execSafeProcess(ffmpegCmd, genArgs, 60000);

  if (!fs.existsSync(testVideoPath)) {
    throw new Error("Failed to generate test video file");
  }

  const probe = await probeMedia(testVideoPath);
  console.log(`✓ Test video generated: ${probe.width}x${probe.height}, ${probe.duration.toFixed(1)}s, hasAudio: ${probe.hasAudio}`);

  // Step 2: Seed or find a test user
  console.log("\n[2/6] Setting up database test user and project...");
  let user = await prisma.user.findFirst({
    where: { email: "test_creator@clipforge.ai" },
  });

  if (!user) {
    user = await prisma.user.create({
      data: {
        email: "test_creator@clipforge.ai",
        name: "Test Creator",
        passwordHash: "test_hash",
        subscription: {
          create: {
            plan: "PRO",
            status: "ACTIVE",
          },
        },
      },
    });
  }
  console.log(`✓ Test user verified (ID: ${user.id})`);

  // Create Project
  const project = await prisma.project.create({
    data: {
      userId: user.id,
      title: "Automated Verification Podcast Clip",
      type: "AUTOCLIP",
      status: "GENERATING",
      platform: "TIKTOK",
      aspectRatio: "VERTICAL_9_16",
      duration: Math.round(probe.duration),
    },
  });

  // Save MediaAsset
  const mediaAsset = await prisma.mediaAsset.create({
    data: {
      userId: user.id,
      projectId: project.id,
      type: "VIDEO",
      name: "test_input_16_9.mp4",
      fileName: "test_input_16_9.mp4",
      filePath: testVideoPath,
      fileSize: fs.statSync(testVideoPath).size,
      mimeType: "video/mp4",
      width: probe.width,
      height: probe.height,
      duration: probe.duration,
      source: "UPLOAD",
    },
  });

  // Create AutoClip Job
  const job = await prisma.videoGenerationJob.create({
    data: {
      userId: user.id,
      projectId: project.id,
      type: "AUTOCLIP",
      status: "QUEUED",
      progress: 0,
      stage: "Queued for automated test",
      input: {
        sourceVideoPath: testVideoPath,
        mediaAssetId: mediaAsset.id,
      },
    },
  });

  console.log(`✓ Database records created (ProjectId: ${project.id}, JobId: ${job.id})`);

  // Step 3: Run the AutoClip Pipeline
  console.log("\n[3/6] Executing executeAutoClipPipeline...");
  await executeAutoClipPipeline({
    jobId: job.id,
    projectId: project.id,
    userId: user.id,
    sourceVideoPath: testVideoPath,
    options: {
      minDuration: 10,
      maxDuration: 25,
      targetCount: 3,
      language: "en",
    },
  });

  // Step 4: Verify generated candidates and transcripts
  console.log("\n[4/6] Inspecting generated clip candidates...");
  const candidates = await prisma.clipCandidate.findMany({
    where: { jobId: job.id },
    orderBy: { score: "desc" },
  });

  console.log(`✓ Total candidates generated: ${candidates.length}`);
  if (candidates.length === 0) {
    throw new Error("No candidates were generated by the pipeline");
  }

  candidates.forEach((c, idx) => {
    console.log(
      `   [Candidate #${idx + 1}] Score: ${c.score}/100 | Time: ${c.startTime.toFixed(1)}s - ${c.endTime.toFixed(1)}s (${c.duration.toFixed(1)}s) | Title: "${c.title}"`
    );
  });

  // Step 5: Render a candidate clip into 9:16 vertical video with subtitles
  const candidateToRender = candidates[0];
  console.log(`\n[5/6] Rendering candidate "${candidateToRender.title}" to vertical 9:16 format with Bold Viral subtitles...`);

  const renderJob = await prisma.videoGenerationJob.create({
    data: {
      userId: user.id,
      projectId: project.id,
      type: "VIDEO_RENDER",
      status: "QUEUED",
      progress: 0,
    },
  });

  const renderResult = await executeRenderClip({
    renderJobId: renderJob.id,
    candidateId: candidateToRender.id,
    projectId: project.id,
    userId: user.id,
    options: {
      cropMode: "center",
      captionPreset: "bold_viral",
      quality: "fast",
    },
  });

  console.log(`✓ Render finished: ExportId: ${renderResult.exportId}, File: ${renderResult.filePath}`);

  // Step 6: Verify rendered output video properties with ffprobe
  console.log("\n[6/6] Verifying rendered video file properties with ffprobe...");
  if (!fs.existsSync(renderResult.filePath)) {
    throw new Error(`Rendered video file not found on disk at ${renderResult.filePath}`);
  }

  const renderedProbe = await probeMedia(renderResult.filePath);
  console.log(`✓ Output Dimensions: ${renderedProbe.width}x${renderedProbe.height} (Target: 1080x1920 vertical)`);
  console.log(`✓ Output Duration: ${renderedProbe.duration.toFixed(2)}s`);
  console.log(`✓ Video Codec: ${renderedProbe.videoCodec}`);
  console.log(`✓ Audio Codec: ${renderedProbe.audioCodec}`);
  console.log(`✓ File Size: ${(fs.statSync(renderResult.filePath).size / 1024).toFixed(1)} KB`);

  // Assertions
  if (renderedProbe.width !== 1080 || renderedProbe.height !== 1920) {
    throw new Error(`Expected 1080x1920 but got ${renderedProbe.width}x${renderedProbe.height}`);
  }

  if (renderedProbe.duration <= 0) {
    throw new Error("Rendered video duration is 0");
  }

  console.log("\n==================================================");
  console.log("✓ ALL AUTOCLIP VERIFICATION CHECKS PASSED 100%!");
  console.log("==================================================");
}

runAutoClipVerification()
  .then(() => {
    process.exit(0);
  })
  .catch((err) => {
    console.error("VERIFICATION FAILED:", err);
    process.exit(1);
  });
